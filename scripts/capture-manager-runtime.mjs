import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repository = resolve(root, "legacy");
const hash = value => createHash("sha256").update(value).digest("hex");
const sourcePath = "src/chat/api-chat-view.ts";
const source = await readFile(resolve(repository, sourcePath), "utf8");
const ast = ts.createSourceFile(sourcePath, source, ts.ScriptTarget.Latest, true);
const matches = [];
function visit(node) {
  if (ts.isStringLiteral(node) && node.text.startsWith("\nIf advertised, choose spawn_workers yourself")) matches.push(node.text);
  ts.forEachChild(node, visit);
}
visit(ast);
if (matches.length !== 1) throw new Error("Original Manager instruction boundary changed.");
const captured = "src/domain/manager-runtime-original.ts";
const text = "// Exact native Manager instruction literal; regenerated by capture-manager-runtime.mjs.\n"
  + `export const originalManagerInstruction = ${JSON.stringify(matches[0])};\n`;
const inspections = [];
for (const path of ["src/chat/worker-tree.ts", "src/chat/worker-result-versions.ts", "src/agent-sessions/agent-session-lifecycle.ts"]) {
  inspections.push({ source: path, sourceSha256: hash(await readFile(resolve(repository, path))) });
}
const manifest = JSON.stringify({
  schema: "pkm.next.domain-capture/v1", sourceRoot: "..", capturedRoot: ".",
  notes: "Only the native Manager instruction literal is captured exactly. Worker identity, handoff and session sources are inspected provenance, not copied or claimed as runnable legacy behavior. The durable scheduler and host adapters are new.",
  files: [{ source: sourcePath, sourceSha256: hash(source), symbols: ["native Manager instruction"], captured, capturedSha256: hash(text) }],
  inspected: inspections,
}, null, 2) + "\n";
for (const [path, content] of [[captured, text], ["migration/manager-runtime-provenance.json", manifest]]) {
  if (process.argv.includes("--check")) {
    if (await readFile(resolve(root, path), "utf8") !== content) throw new Error(`Manager runtime capture differs: ${path}`);
  } else await writeFile(resolve(root, path), content);
}
