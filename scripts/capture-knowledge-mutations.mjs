import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import ts from "typescript";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const serverRoot = resolve(dirname(scriptPath), "..");
const sourceRoot = resolve(serverRoot, "legacy");
const args = process.argv.slice(2);
if (args.some(arg => arg !== "--check")) throw new Error("Usage: node scripts/capture-knowledge-mutations.mjs [--check]");
const check = args.includes("--check");
const hash = value => createHash("sha256").update(value).digest("hex");
const sourceFiles = {
  filestore: {
    path: "src/knowledge/filestore.ts",
    declarations: [
      "parseStoreFrontmatter", "serializeStoreFrontmatter", "safeName", "safeCategory",
      "writeKnowledgeMarkdown", "writeKnowledgeMarkdownUnlocked", "noteFromFile", "noteUpsert", "skillFromFile", "skillUpsert",
      "normalizeCites", "toYear", "paperFromFile", "buildPaperResolver", "citationCounts", "paperUpsert",
    ],
  },
  identity: {
    path: "src/knowledge/knowledge-contracts.ts",
    declarations: ["legacyKnowledgeAlias", "readKnowledgeIdentity", "nextKnowledgeIdentity"],
  },
  markdownAssets: {
    path: "src/knowledge/markdown-assets.ts",
    declarations: ["markdownAssetDirectory", "saveMarkdownAsset", "rebaseMarkdownAssets"],
  },
};
const testPaths = [
  "tests/test-markdown-owned-assets.js",
  "tests/test-todo-board.js",
  "tests/test-knowledge-contracts.js",
  "tests/test-retrieval-snapshot.js",
];

function findDeclaration(text, path, name) {
  const parsed = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
  const matches = parsed.statements.filter(statement =>
    "name" in statement && statement.name && ts.isIdentifier(statement.name) && statement.name.text === name);
  if (matches.length !== 1) throw new Error(`Original Knowledge capture boundary changed: ${path}#${name}`);
  return matches[0].getText(parsed);
}

const captured = {};
const sourceRecords = [];
for (const [key, file] of Object.entries(sourceFiles)) {
  const text = await readFile(resolve(sourceRoot, file.path), "utf8");
  const declarations = Object.fromEntries(file.declarations.map(name => [name, findDeclaration(text, file.path, name)]));
  captured[key] = declarations;
  sourceRecords.push({
    source: file.path, sourceSha256: hash(text),
    declarations: Object.entries(declarations).map(([name, value]) => ({ name, sha256: hash(value) })),
  });
}
const originalTests = Object.fromEntries(await Promise.all(testPaths.map(async path => [
  path, await readFile(resolve(sourceRoot, path), "utf8"),
])));
for (const [source, text] of Object.entries(originalTests)) sourceRecords.push({ source, sourceSha256: hash(text) });

const captureModule = [
  "// Exact original source declarations/tests as inert text; generated by scripts/capture-knowledge-mutations.mjs.",
  `export const capturedDeclarations = ${JSON.stringify(captured, null, 2)} as const;`,
  `export const capturedOriginalTests = ${JSON.stringify(originalTests, null, 2)} as const;`,
  "",
].join("\n");
const capturePath = "src/domain/knowledge-mutations-original.ts";
const provenancePath = "migration/knowledge-mutations-provenance.json";
const provenance = {
  schema: "pkm.domain-capture/v1",
  sourceRoot: "../",
  captureRoot: "next-server",
  transformation: "TypeScript AST selects the named original Note, Skill and Paper upsert/projection, stable identity, citation and asset declarations as inert source text; focused original tests are embedded byte-for-byte. Captures are evidence only and execute no legacy store code.",
  capture: { path: capturePath, sha256: hash(captureModule) },
  script: { path: "scripts/capture-knowledge-mutations.mjs", sha256: hash(await readFile(scriptPath)) },
  files: sourceRecords,
  qualification: "Original behaviors are evidence, not copied host integrations. The new adapter operates only on the isolated Markdown workspace, preserves unowned bytes, does not move/delete documents or assets, and requires the parent shared compound journal/receipt/index transaction. It does not claim migration of the legacy Knowledge Root.",
};
const provenanceText = JSON.stringify(provenance, null, 2) + "\n";

if (check) {
  const [existingCapture, existingProvenance] = await Promise.all([
    readFile(resolve(serverRoot, capturePath), "utf8"),
    readFile(resolve(serverRoot, provenancePath), "utf8"),
  ]);
  if (existingCapture !== captureModule || existingProvenance !== provenanceText) {
    throw new Error("Knowledge mutation captures/provenance are stale; regenerate without --check.");
  }
} else {
  await mkdir(resolve(serverRoot, "src/domain"), { recursive: true });
  await writeFile(resolve(serverRoot, capturePath), captureModule);
  await writeFile(resolve(serverRoot, provenancePath), provenanceText);
}
console.log(`Knowledge mutation capture ${check ? "verified" : "generated"} (${sourceRecords.length} source/test records).`);
