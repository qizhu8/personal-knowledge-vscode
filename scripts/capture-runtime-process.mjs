import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import ts from "typescript";
import { packageRoot, hash, checkCaptureRecords, checkNativeRecords } from "./migration.mjs";

const root = resolve(packageRoot, "legacy");
const target = "src/domain/runtime-process-original.ts";
const provenance = resolve(packageRoot, "migration/runtime-process-provenance.json");
const mode = process.argv.slice(2);
if (mode.length && (mode.length !== 1 || !["--check", "--refresh-native"].includes(mode[0]))) {
  throw new Error("Usage: node scripts/capture-runtime-process.mjs [--check|--refresh-native]");
}
async function nativePins() {
  return Promise.all([
    "src/runtime-process.ts", "src/runtime-process-store.ts", "src/runtime-process-contracts.ts",
    "src/process-bridge.ts",
    "tests/runtime-process-fixtures.mjs", "tests/runtime-process.test.mjs",
    "tests/runtime-process-restart.test.mjs", "tests/process-bridge.test.mjs",
  ].map(async file => ({ file, sha256: hash(await readFile(resolve(packageRoot, file))) })));
}
if (mode.length) {
  const record = JSON.parse(await readFile(provenance, "utf8"));
  const issues = await checkCaptureRecords(record.files, undefined, undefined, {
    dataset: "runtime-runtime-process-historical",
  });
  if (mode[0] === "--check") issues.push(...await checkNativeRecords(record.native ?? []));
  if (issues.length) throw new Error(JSON.stringify(issues));
  if (mode[0] === "--refresh-native") {
    record.native = await nativePins();
    const bytes = JSON.stringify(record, null, 2) + "\n";
    if (bytes !== await readFile(provenance, "utf8")) await writeFile(provenance, bytes);
  }
  console.log(`runtime-process provenance: ${record.files.length} captures verified; ${record.native?.length ?? 0} native pins`);
} else {
  const selections = [
    ["src/runtime/version-order.ts", ["compareVersionOrder"]],
    ["src/mcp/mcp-attribution.ts", ["MCP_ATTRIBUTION_SCHEMA", "ManagedMcpHostContext", "ManagedMcpAttribution"]],
    ["src/runtime/background-processes.ts", [
      "BackgroundProcessRuntime", "BackgroundProcessAssessment", "BackgroundProcess",
      "ProcessObservation", "parseProcessTable", "assessBackgroundProcess",
    ]],
    ["src/runtime/pkm-service.ts", [
      "PKM_SERVICE_PROTOCOL", "PKM_SERVICE_MAX_MESSAGE_BYTES", "PkmServiceVersionError",
      "PkmServiceOfflineError", "PkmServiceExecutionUncertainError", "PkmServiceRecoveryPersistenceError",
    ]],
  ];
  const sources = [];
  const declarations = [];
  for (const [source, names] of selections) {
    const text = await readFile(resolve(root, source), "utf8");
    const parsed = ts.createSourceFile(source, text, ts.ScriptTarget.Latest, true);
    for (const name of names) {
      const matches = parsed.statements.filter(node => node.name?.text === name ||
        (ts.isVariableStatement(node) && node.declarationList.declarations.some(item => item.name.getText(parsed) === name)));
      if (matches.length !== 1) throw new Error(`Runtime process capture boundary changed: ${source}:${name}`);
      declarations.push(matches[0].getText(parsed));
    }
    sources.push({ source, sourceSha256: hash(text), captured: target });
  }
  const captured = `// Generated by scripts/capture-runtime-process.mjs. Pure declarations only; no host inventory or service bootstrap.\n${declarations.join("\n\n")}\n`;
  await writeFile(resolve(packageRoot, target), captured);
  const capturedSha256 = hash(captured);
  await writeFile(provenance, JSON.stringify({
    schema: "pkm.domain-capture/v1",
    transformation: "Exact AST declarations: original version ordering, process-table parsing/assessment, attribution types and service uncertainty/version/recovery errors. No process discovery, filesystem probes, credentials, legacy root, service boot/IPC, sync, chat, workflow, approvals or detached launch. New owned-job persistence and bounded event ring intentionally replace host discovery and diagnostic files, rather than claiming legacy execution equivalence.",
    nativeBoundary: "Only RuntimeProcessService.launch accepts an allowlisted adapter ID through injected trusted authorization; public runtimeProcessDefinitions has status/list/events/cancel only. Adapters are trusted direct-child programs and must not spawn descendants. No group signals, stale PID probes, automatic replay or remote listeners.",
    integration: {
      definitions: "runtime-process-contracts.ts: runtimeProcessDefinitions (schema-only)",
      moduleSchema: "runtime-process-contracts.ts: RUNTIME_PROCESS_MODULE_SCHEMA (pkm.runtime-process.module/v1)",
      service: "runtime-process.ts: RuntimeProcessService",
      repository: "runtime-process-store.ts: RuntimeProcessStore(DatabaseSync, ownerId, eventCapacity, previousOwnerId?)",
      ddl: "runtime-process-store.ts: RUNTIME_PROCESS_DDL (idempotent CREATE TABLE/INDEX; injected database remains caller-owned)",
      tables: ["runtime_process_owner", "runtime_process_jobs", "runtime_process_events"],
      dispatch: "await service.request(authenticatedActorId, {operation,args}) outside SQLite transactions",
      errorAdapter: "RuntimeProcessError exposes code and effect (not-committed|unknown); parent may translate to CoreError without losing either field.",
      shutdown: "await service.close({drainMs}) before closing the injected shared database",
      restart: "Trusted exact-owner CAS previousOwnerId required for an unclosed repository. Old QUEUED/RUNNING -> INTERRUPTED; RUNNING effect unknown. No PID signal or replay.",
      takeoverPrecondition: "Trusted caller must fence/stop the old host before takeover; the module never probes host process liveness.",
      dependencies: "Existing node:sqlite, node:child_process, node:crypto, node:path and zod only. No manifest changes.",
      nativeApi: {
        constructor: "new RuntimeProcessService({repositoryFactory(ownerId,eventCapacity),adapters,authorizeLaunch({actorId,adapterId,input}):Promise<boolean>,limits?})",
        adapter: "{id,executable:absolutePath,cwd?:absolutePath,env?:Record<string,string>,arguments(jsonInput):readonly string[]}; shell:false,detached:false,stdio ignore/pipe/pipe; empty environment by default",
        launch: "launch({actorId,operationId:UUID,adapterId,input:JSON,deadlineMs?}):Promise<RuntimeProcessJob>; durable idempotency key (actorId,operationId) pins canonical input, adapter and deadline",
        status: "status(actorId,jobId):RuntimeProcessJob",
        wait: "wait(actorId,jobId):Promise<RuntimeProcessJob>; completion only after owned direct child close",
        cancel: "cancel(actorId,jobId):Promise<RuntimeProcessJob>; idempotent intent, use wait for terminal receipt",
        request: "request(actorId,{operation,args}):Promise<unknown>; schema-validated public status/list/events/cancel only",
        close: "close({drainMs?}={}):Promise<void>; bounded drain, TERM, grace, KILL, direct-child reaping; rejects on unreconciled persistence or reap failure",
      },
      limits: "Hard ceilings: 4 concurrent,32 queued,4096 retained jobs,128 events/job,65536 bytes/stream,16384 input bytes,128 arguments/32768 argument bytes,300000ms deadline,2000ms TERM grace,30000ms shutdown drain. Config may lower only.",
      limitations: [
        "Trusted adapters must not spawn descendants, detach or invoke a shell; no process-tree termination is claimed. Only currently live direct ChildProcess handles are signalled.",
        "No credential inheritance or remote access is provided. Supplying configured executables/cwd/environment and authenticating the actor are trusted host responsibilities.",
        "Output retains the first per-stream byte cap as base64 and counts all excess discarded bytes; event ring metadata has explicit cursor gaps.",
        "Queue deadline starts at durable admission, not during the trusted authorization callback. In-flight authorization is bounded and cannot launch after close; arbitrary user callbacks cannot be forcibly interrupted.",
        "Receipt history is bounded and fails closed at capacity; archival/removal is an explicit trusted host maintenance concern, never automatic receipt eviction or effect replay.",
        "If persistence fails, new effects are blocked and direct children are reaped. close rejects so the host must reconcile unknown receipts via explicit restart recovery.",
      ],
      fixtures: [
        "tests/runtime-process-fixtures.mjs",
        "tests/runtime-process.test.mjs",
        "tests/runtime-process-restart.test.mjs",
        "tests/runtime-process-original.test.mjs",
      ],
    },
    files: sources.map(source => ({ ...source, capturedSha256 })),
    native: await nativePins(),
  }, null, 2) + "\n");
}
