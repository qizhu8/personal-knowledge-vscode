import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = resolve(root, "legacy");
const hash = value => createHash("sha256").update(value).digest("hex");
const selections = [
  ["src/chat/chat-memory-policy.ts", ["memoryPolicy", "memorySourceTime", "memoryExclusionReason", "memoryAgeAllows"]],
  ["src/chat/task-context-checkpoint.ts", ["currentTaskReport"]],
  ["src/chat/chat-memory.ts", ["chatMemoryQuery", "memoryTerms", "memoryMatchScore", "chatMemorySegments", "recentChatDialogue", "retrieveChatMemory"]],
  ["src/chat/api-chat-models.ts", ["estimateInputTokens"]],
];
let output = `// Generated by scripts/capture-memory-context.mjs from original source functions.\n`
  + `import { createHash } from "node:crypto";\n`
  + `import type { MemoryContextChat as ApiConversation, MemoryContextMessage as ChatMessage,\n`
  + `  MemoryContextPolicy as ChatMemoryPolicy, MemoryHarnessReport as HarnessReport,\n`
  + `  MemoryPromptMessage as ApiChatMessage } from "../memory-context-contracts.js";\n`
  + `const currentHarnessTask = (chat: ApiConversation) => currentTaskReport(chat);\n\n`;
const sources = [];
for (const [path, names] of selections) {
  const raw = await readFile(resolve(sourceRoot, path), "utf8");
  const parsed = ts.createSourceFile(path, raw, ts.ScriptTarget.Latest, true);
  for (const name of names) {
    const matches = parsed.statements.filter(node => ts.isFunctionDeclaration(node) && node.name?.text === name);
    if (matches.length !== 1) throw new Error(`Original function boundary changed: ${path}#${name}`);
    output += matches[0].getText(parsed) + "\n\n";
  }
  sources.push({ source: path, sourceSha256: hash(raw), functions: names });
}
const destination = "src/domain/memory-context-selection.ts";
await writeFile(resolve(root, destination), output);
const originalTests = ["tests/test-chat-memory-recall.js", "tests/test-chat-memory-scope.js", "tests/test-chat-context-mechanisms.js"];
const originalSources = ["src/memory/chat-memory-service.ts", "src/memory/explicit-memory-service.ts",
  "src/chat/chat-memory-scope.ts", "src/chat/chat-context.ts", "src/chat/api-chat-view.ts"];
const files = sources.map(item => ({ ...item, captured: destination, capturedSha256: hash(output) }));
for (const source of [...originalSources, ...originalTests]) {
  const captured = originalSources.includes(source) ? "src/memory-context.ts"
    : source === "tests/test-chat-memory-recall.js" ? "tests/memory-context-original.test.mjs" : "tests/memory-context.test.mjs";
  files.push({ source, sourceSha256: hash(await readFile(resolve(sourceRoot, source))),
    captured, capturedSha256: hash(await readFile(resolve(root, captured))) });
}
const migratedTests = ["tests/memory-context.test.mjs", "tests/memory-context-original.test.mjs"];
const implementation = ["src/memory-context.ts", "src/memory-context-contracts.ts", destination, "scripts/capture-memory-context.mjs"];
const migrated = [];
for (const path of [...implementation, ...migratedTests]) {
  migrated.push({ path, sha256: hash(await readFile(resolve(root, path))) });
}
await writeFile(resolve(root, "migration/memory-context-provenance.json"), JSON.stringify({
  schema: "pkm.domain-capture/v1", sourceRoot: "..", capturedRoot: ".",
  transformation: "AST-extracted original query/segmentation/coverage ranking/age filtering and original UTF-8 token upper-bound function bodies, unchanged. Native injected snapshot/retriever bridge adds actor+namespace+epoch fences, confirmed-current lifecycle filtering, JSON quoted non-authority context and immutable attribution. Original recall fixture file is executed directly by a restricted require adapter without writing or reading private Chat data.",
  files, migrated,
  qualification: "Native context service only; no public capability dispatch, no model generation/network, no lifecycle writes or human-decision bypass. Compute policy/model execution remains injected; no worker dependencies changed. Exact token accounting only when an exact full-prompt counter is supplied; otherwise original byte upper bound.",
}, null, 2) + "\n");
console.log("Captured original memory selection and source/test hashes with explicit repository/package roots.");
