const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const engine = require('../dist/knowledge/asset-classification');
const privacy = require('../dist/knowledge/content-privacy');
const root = path.join(__dirname, `.asset-classification-${process.pid}`);
const write = (file, bytes) => { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), bytes); };
const read = file => fs.readFileSync(path.join(root, file));
function snapshot(directory = root) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(e => e.isDirectory() ? snapshot(path.join(directory, e.name)) :
    [[path.relative(root, path.join(directory, e.name)), fs.readFileSync(path.join(directory, e.name)).toString('base64')]]);
}
try {
  fs.mkdirSync(root);
  const body = 'Record the source evidence before changing shared data. Search existing assets and compare their validation receipts before proposing a reusable procedure. Preserve provenance and use explicit approval for every correction.';
  const original = Buffer.from('\uFEFF---\r\ntitle: Example\r\nknowledgeId: "knowledge_0123456789abcdef01234567"\r\nrevision: 4\r\ncustom:\r\n  nested: preserved\r\n---\r\n' + body + '\r\n');
  write('notes/Engineering/one.md', original);
  write('notes/two.md', body + '\r\n');
  write('skills/near.md', body + ' Additional guidance.' + '\r\n');
  write('scripts/run.py', '# reusable example\nprint("hello")\n');
  write('scripts/.run.py.pkm.json', JSON.stringify({ schema: 'pkm.script/v1', knowledgeId: 'script_aaaaaaaaaaaaaaaaaaaaaaaa', aliases: [] }));
  write('components/example.json', JSON.stringify({ componentId: 'component_test', kind: 'note' }));
  write('actions/example.json', JSON.stringify({ actionId: 'action_test' }));
  write('recipes/example.json', JSON.stringify({ recipeId: 'recipe_test' }));
  write('papers/example.md', '---\nsource_url: "https://example.org"\n---\n# Validation\nVerified sources.');
  write('notes/Secret/private.md', 'PRIVATE_CONTENT_MUST_NOT_APPEAR');
  write('notes/frontmatter-private.md', '---\nprivacy: private\n---\nPRIVATE_FRONTMATTER_SECRET');
  privacy.setPrivacyStoreRoot(root); privacy.setTopLevelPrivacy('notes', 'Secret', true);
  const before = snapshot();
  const writes = ['writeFileSync', 'mkdirSync', 'renameSync', 'unlinkSync', 'rmSync', 'openSync'];
  const saved = Object.fromEntries(writes.map(key => [key, fs[key]]));
  const log = console.log; const logs = [];
  console.log = (...args) => logs.push(args.join(' '));
  let preview;
  try {
    for (const key of writes) fs[key] = () => { throw new Error(`dry-run attempted ${key}`); };
    fs.openSync = (file, flags, ...args) => { assert.equal(flags, "r", "dry-run may only open read-only files"); return saved.openSync(file, flags, ...args); };
    preview = engine.previewAssetClassification(root);
    assert.deepEqual(engine.previewAssetClassification(root), preview);
  } finally { Object.assign(fs, saved); console.log = log; }
  assert.deepEqual(snapshot(), before, 'preview writes nothing');
  assert.equal(preview.modelCalls, 0);
  assert.equal(logs.length, 0);
  assert(!JSON.stringify(preview).includes('PRIVATE_'));
  assert(!JSON.stringify(preview).includes('Secret/'));
  assert(preview.proposals.every(p => p.evidence.length && p.evidence.every(e => e.rule && e.confidence > 0)));
  assert(preview.proposals.some(p => p.type === 'duplicate'));
  assert(preview.proposals.some(p => p.type === 'near-duplicate'));
  assert(preview.proposals.some(p => p.type === 'correction'));
  const classifications = preview.proposals.filter(p => p.type === 'classification');
  assert.equal(new Set(classifications.map(p => p.classification.kind)).size, 7);
  const note = classifications.find(p => p.asset.endsWith('/one.md'));
  const script = classifications.find(p => p.asset === 'scripts/run.py');
  assert.equal(note.locator, 'pkm://knowledge/knowledge_0123456789abcdef01234567');
  assert.equal(script.locator, 'pkm://script/script_aaaaaaaaaaaaaaaaaaaaaaaa');
  assert.throws(() => engine.applyAssetClassification(root, preview, []));
  assert.throws(() => engine.applyAssetClassification(root, preview, ['fabricated']));
  const result = engine.applyAssetClassification(root, preview, [note.id, script.id]);
  assert.deepEqual(result.applied, [note.id, script.id]);
  assert.equal(result.skipped.length, 0);
  assert.equal(read('scripts/run.py').toString(), '# reusable example\nprint("hello")\n');
  assert(fs.existsSync(path.join(root, script.target)));
  assert(!script.target.endsWith('.json'), 'sidecar must not be mistaken for a typed JSON asset');
  assert.equal(read(note.asset).toString().replace(/^pkmClassification:.*\r\n/m, ''), original.toString(), 'only frontmatter changes; BOM/CRLF/body and nested YAML preserved');
  for (const [file, bytes] of before) if (file !== note.asset) assert.equal(read(file).toString('base64'), bytes, `unapproved asset unchanged: ${file}`);
  const journal = JSON.parse(read(`.pkm/state/asset-classification/${result.journalId}.json`));
  assert.equal(journal.entries[0].before, original.toString('base64'));
  assert.equal(fs.statSync(path.join(root, `.pkm/state/asset-classification/${result.journalId}.json`)).mode & 0o777, 0o600);
  assert.equal(engine.rollbackAssetClassification(root, result.journalId).applied.length, 2);
  assert.deepEqual(read(note.asset), original);
  assert(!fs.existsSync(path.join(root, script.target)));
  const stale = engine.previewAssetClassification(root);
  write(note.asset, 'User edited this asset.');
  const rejected = engine.applyAssetClassification(root, stale, [stale.proposals.find(p => p.asset === note.asset && p.type === 'classification').id]);
  assert.equal(rejected.skipped[0].reason, 'changed-since-preview');
  assert.equal(read(note.asset).toString(), 'User edited this asset.');
  const fresh = engine.previewAssetClassification(root);
  const target = fresh.proposals.find(p => p.asset === note.asset && p.type === 'classification');
  const applied = engine.applyAssetClassification(root, fresh, [target.id]);
  write(note.asset, 'Edited after apply');
  assert.equal(engine.rollbackAssetClassification(root, applied.journalId).skipped[0].reason, 'changed-since-apply');
  assert.equal(read(note.asset).toString(), 'Edited after apply');
  const readOnly = fresh.proposals.find(p => p.type === 'correction');
  assert.equal(engine.applyAssetClassification(root, fresh, [readOnly.id]).skipped[0].reason, 'review-only');
  const privatePreview = engine.previewAssetClassification(root);
  const privateProposal = privatePreview.proposals.find(p => p.asset === 'notes/two.md' && p.type === 'classification');
  privacy.setTopLevelPrivacy('notes', 'two.md', true);
  assert.equal(engine.applyAssetClassification(root, privatePreview, [privateProposal.id]).skipped[0].reason, 'privacy-changed-since-preview');
  const guidance = fs.readFileSync('src/chat/knowledge-reader.ts', 'utf8');
  assert(guidance.includes('search existing knowledge before proposing'));
  assert(guidance.includes('not a compulsory promotion ladder'));
  assert(guidance.includes('Do not persist every exchange'));
  assert(guidance.includes('reusable procedural Skills'));
  const bridge = JSON.parse(execFileSync(process.execPath, ['resources/asset_classification.js', process.cwd(), root], { input: '{"operation":"preview"}', encoding: 'utf8' }));
  assert.equal(bridge.modelCalls, 0);
  const source = fs.readFileSync('src/knowledge/asset-classification.ts', 'utf8');
  assert(!/from ["'].*(?:\/ai\/|embedding|chat\/)/.test(source), 'engine has no model dependency');
  assert(!/console\.|fetch\(|https?\.request/.test(source), 'engine has no logging or outbound calls');
  console.log('asset classification: deterministic zero-write dry-run, seven kinds, identities, evidence, subset, metadata-only, stale-hash, exact rollback, privacy, dedupe and zero-model checks passed');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
