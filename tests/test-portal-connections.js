const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const { PortalConnectionJournal, endpointLabel, endpointScope, portalConnectionAccess } = require(process.env.PKM_PORTAL_CONNECTIONS_MODULE || "../dist/chatroom/portal-connections");
const root=path.join(__dirname,".."),journal=new PortalConnectionJournal();
const owner={chatId:"chat-a",chatLabel:"Local Chat",external:false,localMachine:"Linux"};
const binding={pairId:"pair-a",role:"controller",peerName:"Windows",peerChatName:"Remote Chat",peerEndpoint:"ws://10.0.0.5:7345/path?secret=PRIVATE"};
journal.observe(owner,binding);
const live=new Map([[owner.chatId,{pairId:binding.pairId,connected:true}]]);
let snapshot=journal.snapshot(live);
assert.equal(snapshot.active,1);
assert.equal(snapshot.connections[0].endpoint,"ws://10.0.0.5:7345");
assert(!JSON.stringify(snapshot).includes("PRIVATE"));
assert.equal(snapshot.connections[0].resumable,false);
assert.equal(journal.snapshot(new Map()).connections.length,0,"only live bindings are visible");
assert.equal(new PortalConnectionJournal().snapshot(live).connections.length,0,"a new window restores no connection history");
journal.observe(owner,undefined);
assert.equal(journal.snapshot(live).connections.length,0,"disconnect immediately removes the pairing");
journal.observe(owner,binding);
journal.observe({...owner,chatId:"chat-b",chatLabel:"Controlled Chat"},{...binding,role:"controlled"});
assert.equal(journal.snapshot(new Map([...live,["chat-b",{pairId:"pair-a",connected:true}]])).connections.length,2);
const grace={since:Date.now()-1000,deadline:Date.now()+60000};
let reconnecting=journal.snapshot(new Map([[owner.chatId,{pairId:"pair-a",connected:false,reconnecting:grace}]]));
assert.equal(reconnecting.connections.length,1,"a pairing in reconnect grace stays visible while the transport is down");
assert.equal(reconnecting.connections.find(item=>item.chatId===owner.chatId).state,"reconnecting");
assert.deepEqual(reconnecting.connections.find(item=>item.chatId===owner.chatId).reconnecting,grace);
assert.equal(reconnecting.active,0,"reconnecting pairings are not counted as active");
assert.equal(journal.snapshot(new Map([[owner.chatId,{pairId:"other",connected:false,reconnecting:grace}]])).connections.length,0,"grace for another pairing is ignored");
const lease=(over={})=>({chatId:"chat-a",connectionId:"pair-a",closed:false,now:Date.now(),effective:{},pendingFileTransferBatches:[],lastInvalidation:null,
  grants:[{id:"g1",mode:"scoped",permissions:["files-read","pkm-read"],remaining:["files-read","pkm-read"],scopes:{"files-read":["/home/private/folder"]},lifecycle:"fixed",grantedAt:Date.now(),expiresAt:Date.now()+60000}],...over});
let access=portalConnectionAccess("pair-a",lease(),{expiresAt:Infinity});
assert.deepEqual(access.permissions.dimensions,["files-read","pkm-read"]);
assert.equal(access.permissions.mode,"scoped");assert.equal(access.permissions.scoped,true);
assert.deepEqual(access.externalAuthorization,{expiresAt:null},"until-disconnected external access is JSON-safe");
assert(!JSON.stringify(access).includes("/home/private"),"folder scopes never reach the panel");
assert.deepEqual(portalConnectionAccess("pair-b",lease()),{},"leases from another pairing are ignored");
assert.deepEqual(portalConnectionAccess("pair-a",lease({closed:true})),{});
assert.deepEqual(portalConnectionAccess("pair-a",lease({grants:[{...lease().grants[0],expiresAt:Date.now()-1}]}),{expiresAt:Date.now()-1}),{},"expired grants and external access are dropped");
assert.deepEqual(portalConnectionAccess("pair-a",lease({grants:[{...lease().grants[0],mode:"once",remaining:[]}]})),{},"spent once grants are dropped");
assert.equal(portalConnectionAccess("pair-a",lease({grants:[...lease().grants,{...lease().grants[0],id:"g2",mode:"all",scopes:{},expiresAt:null}]})).permissions.expiresAt,null);
access=portalConnectionAccess("pair-a",lease());
const withAccess=journal.snapshot(new Map([[owner.chatId,{pairId:"pair-a",connected:true,access}]]));
assert.deepEqual(withAccess.connections.find(item=>item.chatId===owner.chatId).access,access);
assert.equal(journal.snapshot(new Map([[owner.chatId,{pairId:"pair-a",connected:true,access:{}}]])).connections[0].access,undefined,"empty access stays absent");
assert(journal.forget("pair-a"));
assert.equal(journal.snapshot(live).connections.length,0);

const detail={style:{},innerHTML:"",querySelectorAll:()=>[]},asks=[];
const source=fs.readFileSync(path.join(root,"src/webview/panel/16-portal-connections.js"),"utf8");
const timers=[];
const ui={document:{getElementById:()=>detail},state:{tab:"portalConnections"},setTimeout:(fn,ms)=>{timers.push({fn,ms});return timers.length;},clearTimeout:id=>{if(timers[id-1])timers[id-1].fn=null;},
  esc:value=>String(value??"").replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll(">","&gt;"),ask:(...args)=>asks.push(args)};
vm.createContext(ui);
vm.runInContext(`${source};this.onSnapshot=portalConnectionsOnSnapshot;this.show=showPortalConnectionsTab`,ui);
ui.show();assert.match(detail.innerHTML,/Loading Portal connections/);
journal.observe(owner,binding);snapshot=journal.snapshot(live);
ui.onSnapshot(snapshot);
