assert.match(detail.innerHTML,/Copy magic code/);
assert.doesNotMatch(detail.innerHTML,/pkmportal:/);
const expiry=timers.filter(timer=>timer.fn).at(-1);
assert(expiry&&expiry.ms<=60050,"a pending link schedules a local re-render at expiry");
