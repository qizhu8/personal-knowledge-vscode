  write("change_workitem_state",{id:"first",state:"blocked",blocked_reason:"Waiting for service"});
  assert.equal(read("list_workitems",{states:["blocked"]}).items[0].blockedReason,"Waiting for service");
  write("change_workitem_state",{id:"first",state:"active"});
  assert.throws(()=>write("submit_workitem_result",{id:"first",outcome:"Success",evidence:[]}),/evidence/);
  const done=write("submit_workitem_result",{id:"first",outcome:"Success",evidence:["test://passed"],
    verification:[{layer:"unit",status:"passed",evidence:["test://unit"]}]});
