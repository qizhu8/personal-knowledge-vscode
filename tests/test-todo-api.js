  assert.throws(()=>write("accept_workitem",{id:"first",reason:"Self approve"}),/delegated reviewer/);
  let state=store.noteWorkItemsRead("Team/Board");
  state=store.noteWorkItemCommand("Team/Board",state.digest,{action:"reopen",id:"first",reason:"Delegate reviewer"},user);
