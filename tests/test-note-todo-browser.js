const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { chromium } = require(process.env.PKM_PLAYWRIGHT_PATH || "playwright");
const store = require("../dist/knowledge/filestore");

test("built Note Table/Board/Timeline roundtrips through Markdown, preserves drafts and separates acceptance",async()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),"pkm-note-ui-"));
  const browser=await chromium.launch({headless:true,...(process.env.PKM_CHROMIUM_EXECUTABLE?{executablePath:process.env.PKM_CHROMIUM_EXECUTABLE}:{})});
  try {
    store.setStorePath(root);
    const slug="Team/Tracker";
    store.noteUpsert({slug,category:"Team",title:"Tracker",type:"general",tags:[],content:"Keep this prose and ![asset](Tracker.assets/chart.png)."});
    const page=await browser.newPage({viewport:{width:1080,height:850}});
    const errors=[];
    page.on("pageerror",error=>errors.push(error.message));
    const messages=[];
    let pause=false;
    await page.exposeFunction("host",async message=>{
      messages.push(message);
      if(pause)return;
      const data={slug:message.slug,requestId:message.requestId};
      try{
        if(message.command==="noteTodoCommand"){
          store.noteWorkItemCommand(message.slug,message.expectedDigest,message.operation,{id:"user:local",role:"user"});
        }
        data.snapshot=store.noteWorkItemsRead(message.slug);
        data.content=store.noteGet(message.slug).content;
        data.projects=[{projectId:"project-ui",name:"UI delivery"}];
      }catch(error){data.error=error.message;}
      await page.evaluate(data=>noteTodoResult(data),data);
    });
    await page.setContent('<style>.hidden{display:none!important}:root{--vscode-panel-border:#444;--vscode-foreground:#ddd;--vscode-descriptionForeground:#aaa;--vscode-editor-background:#181818;--vscode-input-background:#222;--vscode-input-foreground:#ddd;--vscode-sideBar-background:#252525;--vscode-focusBorder:#49c;--vscode-charts-blue:#49c;--vscode-charts-green:#8b6;--vscode-errorForeground:#f88}body{background:#181818;color:#ddd}</style><nav><button data-note-view="markdown">Markdown</button><button data-note-view="table">Table</button><button data-note-view="board">Board</button><button data-note-view="timeline">Timeline</button></nav><div id="note-todo" class="hidden"></div><div id="note-markdown"></div><input id="outside">');
    await page.addStyleTag({path:path.resolve(__dirname,"../dist/webview/panel.css")});
    const source=fs.readFileSync(path.resolve(__dirname,"../src/webview/panel/22-note-todo.js"),"utf8");
    const built=fs.readFileSync(path.resolve(__dirname,"../dist/webview/panel.js"),"utf8");
    assert(built.includes(source),"exercise the exact shipped Todo module");
    await page.addScriptTag({content:`const esc = s => String(s??'').replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;').replace(/'/g,'&#39;');
      let currentDetail={type:'note',slug:'Team/Tracker',title:'Tracker',category:'Team',content:'Keep this prose and ![asset](Tracker.assets/chart.png).'};
      const vscode={postMessage:message=>host(message)};
      const safeMarked=content=>esc(content);
      const ask=(command,args)=>vscode.postMessage({command,...args});
      const pkModal=options=>options.onOk('Reviewed explicit evidence');
      ${source}`});
    await page.evaluate(()=>noteTodoMount(currentDetail));
    assert.equal(messages.length,0,"ordinary Markdown opening must not scan or start a tracker");
    await page.evaluate(()=>noteTodoShow("table"));
    await page.getByText("No explicit Work Items.",{exact:false}).waitFor();
    const reads=messages.length;
    await page.evaluate(()=>noteTodoMount(currentDetail));
    await page.waitForFunction(()=>noteTodo.pending===null);
    assert.equal(messages.length,reads+1,"explicit Note reopening reads a fresh digest rather than reviving a stale projection");
    await page.getByRole("button",{name:"New Work Item",exact:true}).click();
    const form=page.locator("#note-todo-editor");
    await form.locator('[name=title]').fill("Deliver <safe> tracker");
    await form.locator('[name=goal]').fill("Track evidence");
    await form.locator('[name=scope]').fill("Note UI only");
    await form.locator('[name=acceptance]').fill("Browser roundtrip\nNo prose rewrite");
    await form.locator('[name=projectId]').selectOption("project-ui");
    await form.locator('[name=plannedStart]').fill("2026-11-01");
    await form.locator('[name=plannedEnd]').fill("2026-11-05");
    await form.getByRole("button",{name:"Save Work Item"}).click();
    await page.waitForFunction(()=>noteTodo.pending===null&&noteTodo.editor===null&&noteTodo.snapshot?.items.length===1);
    assert.equal(await page.locator(".note-todo-table > tbody > tr").count(),1);
    assert.equal(await page.locator(".note-todo-table strong").innerText(),"Deliver <safe> tracker");
    let item=store.noteWorkItemsRead(slug).items[0];
    assert.equal(item.projectId,"project-ui");
    assert.equal(item.acceptance.length,2);
    assert.match(store.noteGet(slug).content,/Keep this prose and !\[asset\]\(Tracker.assets\/chart.png\)\./);
    await page.evaluate(()=>noteTodoShow("board"));
    assert.equal(await page.locator(".note-todo-card").count(),1);
    assert.equal(await page.locator(".note-todo-swimcell").count(),5);
    await page.locator("#note-todo-filter").fill("Deliver");
    await page.locator("#note-todo-filter").dispatchEvent("change");
    assert.equal(await page.locator(".note-todo-card").count(),1);
    await page.locator("#note-todo-filter").fill("");
    await page.locator("#note-todo-filter").dispatchEvent("change");
    assert.equal(await page.locator(".note-todo-card").count(),1,"focused filter changes must not re-enter rendering on blur");
    await page.getByRole("button",{name:"Details / Edit",exact:true}).click();
    await form.locator('[name=goal]').fill("Unsent draft survives");
    await form.locator('[name=goal]').focus();
    const draftHandle=await form.locator('[name=goal]').elementHandle();
    await page.evaluate(()=>{
      if(!noteTodoDetailRefresh({...currentDetail,content:currentDetail.content+"\nExternal update"})) throw Error("Detail refresh was not intercepted");
      for(let index=0;index<10;index++)noteTodoDetailRefresh({...currentDetail});
    });
    assert.equal(await draftHandle.evaluate(node=>node===document.activeElement&&node.isConnected),true);
    assert.equal(await form.locator('[name=goal]').inputValue(),"Unsent draft survives");
    // Change the real Note behind the UI to reproduce the original CAS conflict.
    fs.appendFileSync(path.join(root,"notes",slug+".md"),"\nExternal prose survives.\n");
    await form.getByRole("button",{name:"Save Work Item"}).click();
    await page.locator('[role=alert]').waitFor();
    assert.equal(await form.locator('[name=goal]').inputValue(),"Unsent draft survives");
    await page.getByRole("dialog").getByRole("button",{name:"Reload from Note"}).click();
    await page.waitForFunction(()=>noteTodo.pending===null);
    assert.equal(await form.locator('[name=goal]').inputValue(),"Unsent draft survives","explicit reload retains the local draft");
    await form.locator('[name=reason]').fill("User extends the goal after reviewing external changes");
    await form.getByRole("button",{name:"Save Work Item"}).click();
    await page.waitForFunction(()=>noteTodo.pending===null&&noteTodo.editor===null);
    await page.getByRole("button",{name:"Details / Edit",exact:true}).click();
    await form.locator('[name=state]').selectOption("Done");
    await form.locator('[name=outcome]').selectOption("Success");
    await form.locator('[name=evidence]').fill("test://browser/roundtrip");
    await form.locator('[name=verify-unit]').selectOption("passed");
    await form.locator('[name=evidence-unit]').fill("node --test tests/test-note-todo-tools.js");
    await form.locator('[name=reason-functional]').fill("UI browser smoke covered separately");
    await form.locator('[name=reason]').fill("User records test result");
    await form.getByRole("button",{name:"Save Work Item"}).click();
    await page.waitForFunction(()=>noteTodo.pending===null&&noteTodo.editor===null);
    assert.equal(await page.locator('.note-todo-swimcell[data-state=Done] .note-todo-card').count(),1,"completed items appear in their own column by default");
    await page.locator("#note-todo-show-done").uncheck();
    assert.equal(await page.locator(".note-todo-swimcell .note-todo-card").count(),0,"completed items can be explicitly hidden");
    await page.locator("#note-todo-show-done").check();
    assert.match(await page.locator(".note-todo-card").innerText(),/awaiting acceptance/);
    await page.getByRole("button",{name:"Accept",exact:true}).click();
    await page.waitForFunction(()=>noteTodo.pending===null&&!!noteTodo.snapshot.items[0].acceptanceDecision);
    assert.equal(store.noteWorkItemsRead(slug).items[0].acceptanceDecision.by,"user:local");
    await page.evaluate(()=>noteTodoShow("timeline"));
    assert.equal(await page.locator(".note-todo-time.plan").count(),1);
    assert.equal(await page.locator(".note-todo-timeline-row").count(),1);
    assert.match(await page.locator(".note-todo-timeline").innerText(),/not measured model compute time/);
    await page.evaluate(()=>noteTodoShow("board"));
    await page.getByRole("button",{name:"Reopen",exact:true}).click();
    await page.waitForFunction(()=>noteTodo.pending===null&&noteTodo.snapshot.items[0].state==="Planning");
    item=store.noteWorkItemsRead(slug).items[0];
    assert.equal(item.outcome,undefined);
    assert.equal(item.acceptanceDecision,undefined);
    assert(item.history.length>=4);
    assert.match(store.noteGet(slug).content,/External prose survives/);
    // A reply from a different Note or an old request must not replace the active board.
    pause=true;
    await page.evaluate(()=>noteTodoLoad());
    await page.evaluate(()=>noteTodoResult({slug:"Other/Note",requestId:noteTodo.pending.requestId,snapshot:{digest:"bad",items:[]}}));
    assert.equal(await page.locator(".note-todo-card").count(),1);
    await page.evaluate(()=>{
      noteTodo.pending=null;
      noteTodoShow("timeline");
      const container=document.createElement("section");container.id="project-note-todos";container.dataset.projectId="project-ui";document.body.append(container);
      noteTodoProjectViews.set("project-ui",{requestId:999});
      noteTodoProjectResult({projectId:"project-ui",requestId:999,records:noteTodo.snapshot.items.map(item=>({slug:noteTodo.slug,item}))});
    });
    assert.equal(await page.locator("#project-note-todos .note-todo-timeline-row").count(),1);
    await page.locator("#project-note-todos > details > summary").filter({hasText:"Recorded state timeline"}).click();
    await page.locator("#project-note-todos .note-todo-timeline-row > details > summary").click();
    assert.equal(await page.locator("#project-note-todos").getByRole("button",{name:"Open Note"}).count(),1);
    await page.setViewportSize({width:390,height:850});
    await page.evaluate(()=>noteTodoShow("board"));
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),true,"narrow Board scrolls inside its lanes, not the entire page");
    await page.evaluate(()=>{
      noteTodo.snapshot.items[0].plannedStart=undefined;
      noteTodo.snapshot.items[0].plannedEnd=undefined;
      noteTodoShow("timeline");
    });
    assert.equal(await page.locator("#note-todo .note-todo-time.plan").count(),0);
    assert.match(await page.locator("#note-todo .note-todo-timeline").innerText(),/Unscheduled/);
    await page.setViewportSize({width:1080,height:850});
    await page.evaluate(()=>{noteTodoShow('board');noteTodoEdit(undefined,'UserStory');});
    await form.locator('[name=title]').fill("As a manager, inspect delivery");
    await form.locator('[name=goal]').fill("See which work delivers user value");
    await form.locator('[name=scope]').fill("Taskboard hierarchy");
    await form.locator('[name=acceptance]').fill("Story row contains its tasks under their actual states");
    await form.getByRole("button",{name:"Save Work Item"}).click();
    pause=false;
    // The test paused Host replies above; finish this explicit user write now.
    const storyWrite=messages.at(-1);
    const result=store.noteWorkItemCommand(slug,storyWrite.expectedDigest,storyWrite.operation,{id:"user:local",role:"user"});
    await page.evaluate(data=>noteTodoResult(data),{slug,requestId:storyWrite.requestId,snapshot:result,content:store.noteGet(slug).content});
    const story=result.items.find(item=>item.kind==="UserStory");
    assert(story);
    assert.equal(await page.locator(`[data-todo-toggle-story="${story.id}"]`).getAttribute("aria-expanded"),"false","new Stories start collapsed");
    await page.locator(`[data-todo-toggle-story="${story.id}"]`).click();
    await page.locator(".note-todo-swimcell [data-todo-edit]").click();
    await form.locator('[name=parentId]').selectOption(story.id);
    await form.getByRole("button",{name:"Save Work Item"}).click();
    await page.waitForFunction(()=>noteTodo.pending===null&&noteTodo.editor===null);
    const row=page.locator(`[data-story-row="${story.id}"]`);
    assert.equal(await row.locator(".note-todo-swimstory .note-todo-card").count(),1);
    assert.equal(await row.locator('.note-todo-swimcell[data-state=Planning] .note-todo-card').count(),1);
    assert.equal(await row.locator('.note-todo-swimcell[data-state=WIP] .note-todo-card').count(),0);
    await row.locator("[data-todo-toggle-story]").click();
    assert.equal(await row.locator(".note-todo-swimcell .note-todo-card").count(),0);
    assert.equal(await row.locator("[data-todo-toggle-story]").getAttribute("aria-expanded"),"false");
    await page.locator("[data-todo-expand-all]").click();
    assert.equal(await row.locator(".note-todo-swimcell .note-todo-card").count(),1);
    await page.locator("[data-todo-collapse-all]").click();
    assert.equal(await row.locator(".note-todo-swimcell .note-todo-card").count(),0);
    await page.locator("[data-todo-expand-all]").click();
    await page.evaluate(()=>noteTodoShow('table'));
    assert.match(await page.locator(".note-todo-table > tbody > tr .note-todo-parent").innerText(),/As a manager/);
    await page.setViewportSize({width:390,height:850});
    await page.evaluate(()=>noteTodoShow('board'));
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),true);
    assert.deepEqual(errors,[]);
  }finally{await browser.close();fs.rmSync(root,{recursive:true,force:true});}
});
